def lesson(level, seed):
    rng = random.Random(seed)
    pairs = UNITS[level][2]
    questions = []
    for reverse in (False, True):
        for index, pair in enumerate(pairs):
            source, answer = (pair[1], pair[0]) if reverse else pair
            others = [p[0 if reverse else 1] for i, p in enumerate(pairs) if i != index]
            choices = rng.sample(others, 3) + [answer]
            rng.shuffle(choices)
            questions.append(dict(prompt=f'Выберите перевод: {source}', choices=choices,
                                  correct=choices.index(answer), explanation=f'{pair[0]} — {pair[1]}'))
    rng.shuffle(questions)
    return questions
